/**
 * AI 聊天 - 联网搜索意图判定规则 (纯函数, 零外部依赖)
 *
 * 用于"自动"搜索模式下判断当前提问是否需要实时联网信息。
 * 判定优先级 (必须保持此顺序):
 *   ③ 明确无需搜索 (本地规则, 高置信度)  → NO_SEARCH
 *   ④ 明显需要实时信息 (本地规则, 高置信度) → SEARCH
 *   ⑤ 模糊问题  → UNCERTAIN (交由小模型分类器兜底)
 */

// ③ 明确无需搜索的高置信度任务 (本地规则, 零成本零延迟)
const NO_SEARCH_PATTERNS = [
	// 纯数学表达式 (仅数字与运算符)
	/^[\d\s+\-*\/^().,=<>%!?×÷:：]+$/,
	// 数学计算 / 单位换算指令
	/(计算|算一下|解方程|求值|乘以|除以|加起来|之和|之差)/,
	// 翻译
	/(翻译|译成|translate)/i,
	// 改写 / 润色 / 扩写 / 缩写
	/(润色|改写|缩写|扩写|压缩成|精简|美化|口语化|书面化|润稿|改得|风格)/,
	// 对用户已提供内容的总结 / 提炼 / 分析
	/(总结|概括|提炼|归纳|分析).{0,12}(这段|以下|下面|以上|这个|这篇|这份|刚才|我发|上面)/,
	// 自包含代码任务 (解释/修复/编写/改写已有代码)
	/(解释|讲解|修复|排查|改成|改写成|帮我写|实现一个|写一个).{0,12}(代码|组件|函数|接口|脚本|这段|这个文件|Bug|bug)/,
	// 对已有代码的改造指令 (反序, 如 "把这个函数改成 async/await")
	/(把|将).{0,10}(改成|转成|换成|改写|重构)/,
	// 简短跟进 / 问候语 (无新增信息需求)
	/^(你好|您好|hi|hello|嗨|哈喽|谢谢|感谢|再见|拜拜|好的|嗯|是的|继续|然后呢|为什么|再说|详细一点|再详细|太长了|缩短|简短|换一个|换个|重新|再来一次|举个例子|展开说说)[\s，。！？!?,.~～、]*$/i,
	// 对上一轮回答的追问 / 精简指令
	/(太长了|太啰嗦|再短一点|缩短|简洁一点|精简一下|再详细|详细一点|继续说|继续讲|换个说法)/,
]

/**
 * ③ 明确无需搜索 (高置信度)
 */
export function rule_explicitNoSearch(query) {
	return NO_SEARCH_PATTERNS.some(pattern => pattern.test(query))
}

// ④ 明显需要实时信息
const EXPLICIT_SEARCH_PATTERNS = /(帮我查|查一下|查查|搜一下|搜搜|搜索|联网|上网查|查找|帮我找|找一下|查资料|搜资料|最新消息|最新进展|最新情况)/
const STRONG_REALTIME_WORDS = [
	'新闻',
	'消息',
	'股价',
	'股票',
	'汇率',
	'天气',
	'比分',
	'赛程',
	'排行',
	'排名',
	'发布',
	'版本',
	'行情',
	'市值',
	'公告',
	'比赛',
	'赛事',
	'金价',
	'油价',
	'利率',
	'大盘',
	'指数',
	'涨幅',
	'财报',
	'发布会',
	'新品',
	'政策',
	'热门',
]

/**
 * ④ 明显需要实时信息 (高置信度)
 */
export function rule_needRealtime(query) {
	if (EXPLICIT_SEARCH_PATTERNS.test(query)) return true
	return STRONG_REALTIME_WORDS.some(word => query.includes(word))
}

/**
 * 自动模式规则判定 (优先级: ③ 明确无需搜索 必须 先于 ④ 明显需要实时信息)
 * 返回: 'NO_SEARCH' | 'SEARCH' | 'UNCERTAIN' (模糊, 交由小模型分类器)
 */
export function decide_searchByRule(query) {
	if (!query) return 'NO_SEARCH'
	// ③ 明确无需搜索: 数学/翻译/改写/总结已提供内容/自包含代码任务/简短跟进
	if (rule_explicitNoSearch(query)) return 'NO_SEARCH'
	// ④ 明显需要实时信息: 显式搜索意图 / 强实时名词
	if (rule_needRealtime(query)) return 'SEARCH'
	// ⑤ 模糊问题交由小模型分类
	return 'UNCERTAIN'
}
